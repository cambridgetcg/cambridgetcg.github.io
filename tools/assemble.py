#!/usr/bin/env python3
"""Lay staged doors into this repository and regenerate the hall.

    python3 tools/assemble.py STAGE_DIR APPROVED_SLUGS_FILE DESCRIPTIONS_JSON

STAGE_DIR holds one directory per door, each with door.json and either a
jekyll/ or a static/ tree that has already passed review. Only slugs listed
in APPROVED_SLUGS_FILE are laid in. DESCRIPTIONS_JSON maps a door's slug to
its one-line description. Regenerates doors.json, index.html, 404.html and
watch/doors.txt.
"""
import html
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SITE = "https://cambridgetcg.github.io"


def lay_in(stage, slug):
    door = json.loads((stage / slug / "door.json").read_text(encoding="utf-8"))
    for kind in ("jekyll", "static"):
        target = REPO / kind / slug
        if target.exists():
            shutil.rmtree(target)
    for kind in ("jekyll", "static"):
        source = stage / slug / kind
        if source.is_dir():
            shutil.copytree(source, REPO / kind / slug)
            door["_kind"] = kind
    return door


def hall(doors):
    items = []
    for door in doors:
        name = html.escape(door["slug"])
        note = html.escape(door["description"] or "")
        moved = door["mode"].split(":", 1)[1] if ":" in door["mode"] else ""
        where = f'<span class="moved">now at {html.escape(moved)}</span>' if moved else ""
        items.append(
            f'      <li><a href="/{name}/"><span class="name">{name}</span>'
            f'<span class="note">{note}</span>{where}</a></li>'
        )
    return TEMPLATE.replace("{{DOORS}}", "\n".join(items)).replace("{{COUNT}}", str(len(doors)))


def main():
    stage, approved_file, descriptions_file = (Path(p) for p in sys.argv[1:4])
    approved = [s.strip() for s in approved_file.read_text().split() if s.strip()]
    descriptions = json.loads(descriptions_file.read_text(encoding="utf-8"))

    for kind in ("jekyll", "static"):
        (REPO / kind).mkdir(exist_ok=True)

    doors = []
    for slug in sorted(approved, key=str.lower):
        door = lay_in(stage, slug)
        doors.append({
            "slug": slug,
            "url": f"{SITE}/{slug}/",
            "mode": door.get("mode", door["_kind"]),
            "built_with": door["_kind"],
            "source_repo": door.get("source_repo"),
            "source_sha": door.get("source_sha"),
            "source_visibility": "private",
            "description": descriptions.get(slug, ""),
            # Count what was left out without naming it: a file name or a
            # description of private material would publish what it describes.
            "items_left_out": len(door.get("removed", [])),
        })

    (REPO / "doors.json").write_text(
        json.dumps({"site": SITE, "doors": doors}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    (REPO / "index.html").write_text(hall(doors), encoding="utf-8")

    # Doors that moved: redirects carry deeper paths to the new home,
    # notices send every path to the new home's front page.
    moved = {}
    for door in doors:
        kind, _, home = door["mode"].partition(":")
        if kind in ("redirect", "notice") and home:
            moved[door["slug"]] = [home, kind == "redirect"]
    page = (REPO / "404.html").read_text(encoding="utf-8")
    start = page.index("/*MOVED*/") + len("/*MOVED*/")
    end = page.index(";", start)
    page = page[:start] + json.dumps(moved, ensure_ascii=False) + page[end:]
    (REPO / "404.html").write_text(page, encoding="utf-8")

    estate = (REPO / "watch" / "estate.txt").read_text(encoding="utf-8")
    lines = ["# Generated by tools/assemble.py: the doors served from this repository,",
             "# followed by watch/estate.txt.", f"{SITE}/ the hall"]
    lines += [f"{d['url']} {d['slug']}" for d in doors]
    (REPO / "watch" / "doors.txt").write_text("\n".join(lines) + "\n\n" + estate, encoding="utf-8")
    print(f"laid in {len(doors)} doors")


