#!/usr/bin/env python3
"""Write the origin's sitemap.xml and robots.txt from doors.json and the copies.

    python3 tools/sitemap.py          # write sitemap.xml and robots.txt
    python3 tools/sitemap.py --check  # exit 1 if either file is out of date

sitemap.xml lists the hall and the front page of every door that is served
here. It leaves out doors that moved (their pages point to the new home), and
any front page that points elsewhere with rel="canonical", asks not to be
indexed, or sends visitors elsewhere with an instant refresh. A refresh to
another page of the same door lists that page instead.

robots.txt keeps allowing every crawler. Crawlers read robots.txt only at the
origin root, so a door's own robots.txt below /<door>/ is never consulted;
this file names the doors' own sitemaps instead. A door's sitemap.xml is named
only when every address in it belongs to that door and is a page this
repository serves, with no rel="canonical" pointing elsewhere and no noindex.

Every check here reads the repository, not the network: a page is "served"
when the file GitHub Pages would answer with exists in jekyll/<door>/ or
static/<door>/ (see served_file). tools/assemble.py runs this after it
regenerates doors.json.
"""
import html
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib.parse import quote, unquote, urljoin, urlsplit

REPO = Path(__file__).resolve().parent.parent
SITE = "https://cambridgetcg.github.io"
NS = "{http://www.sitemaps.org/schemas/sitemap/0.9}"

ROBOTS_HEAD = (
    "# Every crawler may read every page here, AI training crawlers included.\n"
    "# Generated by tools/sitemap.py from doors.json and the copies.\n"
    "User-agent: *\n"
    "Allow: /\n"
)

CANONICAL = re.compile(r"<link\b[^>]*\brel=[\"']?canonical[\"']?[^>]*>", re.I)
HREF = re.compile(r"\bhref=[\"']([^\"']+)[\"']", re.I)
ROBOTS_META = re.compile(r"<meta\b[^>]*\bname=[\"']?robots[\"']?[^>]*>", re.I)
REFRESH = re.compile(r"<meta\b[^>]*\bhttp-equiv=[\"']?refresh[\"']?[^>]*>", re.I)
CONTENT = re.compile(r"\bcontent=[\"']([^\"']*)[\"']", re.I)


def doors(repo):
    return json.loads((repo / "doors.json").read_text(encoding="utf-8"))["doors"]


def moved(door):
    return ":" in door["mode"]


def door_root(repo, slug):
    """The door's source directory and how GitHub Pages serves it."""
    for kind in ("static", "jekyll"):
        path = repo / kind / slug
        if path.is_dir():
            return path, kind
    return None, None


def served_file(repo, url):
    """The repository file GitHub Pages answers `url` with (200, no redirect), or None.

    static/<door>/ files are served as they are; GitHub Pages also answers
    /x with x.html, and /dir/ with dir/index.html. jekyll/<door>/ is built:
    x.md becomes x.html, and a folder without index.html or index.md uses its
    README.md. Paths with a part starting with "_" or "." are not built.
    A folder addressed without its trailing slash is a redirect, so None.
    """
    parts = urlsplit(url)
    if f"{parts.scheme}://{parts.netloc}" != SITE or parts.query or parts.fragment:
        return None
    path = unquote(parts.path)
    if path == "/":
        return repo / "index.html"
    slug, _, rest = path.lstrip("/").partition("/")
    root, kind = door_root(repo, slug)
    if root is None:
        return None
    if path == f"/{slug}":
        return None  # GitHub Pages redirects to /<door>/
    if kind == "jekyll" and any(p[:1] in "_." for p in rest.split("/") if p):
        return None
    target = root / rest
    if rest == "" or rest.endswith("/"):
        names = ["index.html"] if kind == "static" else ["index.html", "index.md", "README.md"]
        return next((target / n for n in names if (target / n).is_file()), None)
    if kind == "static":
        if target.is_file():
            return target
        if target.is_dir() and (target / "index.html").is_file():
            return None  # redirected to the folder
        page = target.with_name(target.name + ".html")
        return page if page.is_file() else None
    stem, dot, ext = target.name.rpartition(".")
    if ext == "html" and dot:
        candidates = [target, target.with_name(stem + ".md")]
    elif target.suffix:
        candidates = [target] if target.suffix != ".md" else []
    else:
        if target.is_dir() and any((target / n).is_file() for n in ("index.html", "index.md", "README.md")):
            return None  # redirected to the folder
        candidates = [target, target.with_name(target.name + ".html"), target.with_name(target.name + ".md")]
    return next((c for c in candidates if c.is_file()), None)


def attribute(tag, pattern):
    found = pattern.search(tag)
    return html.unescape(found.group(1)) if found else None


def page_signals(path):
    """(canonical, noindex, instant refresh target) read from an HTML file."""
    if path.suffix != ".html":
        return None, False, None
    text = path.read_text(encoding="utf-8", errors="ignore")
    canonicals = [attribute(tag, HREF) for tag in CANONICAL.findall(text)]
    canonical = next((c for c in canonicals if c), None)
    noindex = any("noindex" in (attribute(tag, CONTENT) or "").lower() for tag in ROBOTS_META.findall(text))
    refresh = None
    for tag in REFRESH.findall(text):
        delay, _, rest = (attribute(tag, CONTENT) or "").partition(";")
        target = re.sub(r"^\s*url\s*=\s*", "", rest, flags=re.I).strip().strip("'\"")
        if delay.strip() in ("0", "") and target:
            refresh = target
    return canonical, noindex, refresh


def check_page(repo, url):
    """(problem, refresh target) for `url` as a sitemap entry. No problem: it belongs."""
    path = served_file(repo, url)
    if path is None:
        return "not served here", None
    canonical, noindex, refresh = page_signals(path)
    if noindex:
        return "asks not to be indexed", None
    if refresh:
        return f"refreshes to {urljoin(url, refresh)}", urljoin(url, refresh)
    if canonical and urljoin(url, canonical) != url:
        return f"canonical is {urljoin(url, canonical)}", None
    return None, None


def page_problem(repo, url):
    """Why `url` does not belong in a sitemap of this origin, or None."""
    return check_page(repo, url)[0]


def front_pages(repo):
    """The pages sitemap.xml lists, and [(door url, why)] for the doors it leaves out."""
    listed, left_out = [f"{SITE}/"], []
    for door in doors(repo):
        url = door["url"]
        if moved(door):
            left_out.append((url, f"moved: {door['mode']}"))
            continue
        why, target = check_page(repo, url)
        if target and target.startswith(url) and page_problem(repo, target) is None:
            listed.append(target)  # the door's front page sends visitors to this page of the door
        elif why:
            left_out.append((url, why))
        else:
            listed.append(url)
    return listed, left_out


def door_sitemap(repo, door):
    """(url, problem) for the door's own sitemap.xml, or None when it has none."""
    root, _ = door_root(repo, door["slug"])
    if root is None or moved(door) or not (root / "sitemap.xml").is_file():
        return None
    url = door["url"] + "sitemap.xml"
    try:
        tree = ET.parse(root / "sitemap.xml")
    except ET.ParseError as err:
        return url, f"not XML: {err}"
    if tree.getroot().tag != NS + "urlset":
        return url, "not a urlset"
    locs = [(el.text or "").strip() for el in tree.getroot().iter(NS + "loc")]
    if not locs:
        return url, "lists nothing"
    for loc in locs:
        if not loc.startswith(door["url"]):
            return url, f"lists an address outside the door: {loc}"
        why = page_problem(repo, loc)
        if why:
            return url, f"{loc}: {why}"
    return url, None


def door_sitemaps(repo):
    found = [s for s in (door_sitemap(repo, d) for d in doors(repo)) if s]
    return [u for u, why in found if why is None], [(u, why) for u, why in found if why]


def loc(url):
    parts = urlsplit(url)
    return html.escape(f"{parts.scheme}://{parts.netloc}{quote(unquote(parts.path), safe='/-._~!$&()*+,;=:@')}", quote=False)


def render_sitemap(urls):
    rows = "\n".join(f"  <url><loc>{loc(u)}</loc></url>" for u in urls)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f"{rows}\n</urlset>\n")


def render_robots(sitemaps):
    lines = [f"Sitemap: {SITE}/sitemap.xml"] + [f"Sitemap: {u}" for u in sitemaps]
    return ROBOTS_HEAD + "\n" + "\n".join(lines) + "\n"


def build(repo=REPO):
    listed, left_out = front_pages(repo)
    named, refused = door_sitemaps(repo)
    files = {"sitemap.xml": render_sitemap(listed), "robots.txt": render_robots(named)}
    return files, left_out, refused


def write(repo=REPO):
    files, left_out, refused = build(repo)
    for name, text in files.items():
        (repo / name).write_text(text, encoding="utf-8")
    return files, left_out, refused


def main(argv):
    check = "--check" in argv
    files, left_out, refused = build(REPO)
    for url, why in left_out:
        print(f"not listed: {url} ({why})")
    for url, why in refused:
        print(f"door sitemap not named in robots.txt: {url} ({why})")
    stale = [name for name, text in files.items()
             if not (REPO / name).is_file() or (REPO / name).read_text(encoding="utf-8") != text]
    if check:
        for name in stale:
            print(f"{name} is out of date: run python3 tools/sitemap.py")
        return 1 if stale else 0
    write(REPO)
    print(f"sitemap.xml lists {files['sitemap.xml'].count('<loc>')} pages; "
          f"robots.txt names {files['robots.txt'].count('Sitemap:')} sitemaps")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
